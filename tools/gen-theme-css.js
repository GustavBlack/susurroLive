#!/usr/bin/env node
'use strict';
/**
 * Generates src/renderer/theme/themes.css from src/renderer/theme/themes.js
 * (the single source of truth for the v1.5 theme palettes).
 *
 * Each theme x mode becomes a [data-theme="id"][data-theme-mode="mode"] block
 * holding the lab primitives, the derived legacy Warm Ink token ladder, and
 * the diarization speaker colors. Regenerate after editing themes.js:
 *
 *   node tools/gen-theme-css.js
 */
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const OUT = path.join(ROOT, 'src', 'renderer', 'theme', 'themes.css');
const OUT_JSON = path.join(ROOT, 'src', 'renderer', 'theme', 'themes.json');

async function main() {
  const { THEMES, deriveTokens, speakerColors } = await import(
    'file:///' + path.join(ROOT, 'src', 'renderer', 'theme', 'themes.js').replace(/\\/g, '/')
  );

  const chunks = [
    '/* susurroLive — theme palettes. GENERATED by tools/gen-theme-css.js from',
    ' * src/renderer/theme/themes.js (the v1.5 Theme Lab source of truth).',
    ' * Do not edit by hand — edit themes.js and regenerate.',
    ' *',
    ' * tokens.css keeps the Warm Ink defaults on :root; these blocks override',
    ' * them when <html data-theme=... data-theme-mode=...> is set. Style rules',
    ' * under html.theme-anim (style.css) animate the swap: chrome surfaces lead',
    ' * at 0 ms, content follows 111 ms later, both over 667 ms.',
    ' */',
    '',
  ];

  for (const theme of THEMES) {
    for (const mode of ['dark', 'light']) {
      const tokens = deriveTokens(theme[mode], mode);
      const spk = speakerColors(theme[mode], mode);
      const lines = [`[data-theme="${theme.id}"][data-theme-mode="${mode}"] {`];
      lines.push(`  /* ${theme.name} — ${theme.vibe} */`);
      for (const [k, v] of Object.entries(tokens)) lines.push(`  ${k}: ${v};`);
      spk.forEach((c, i) => lines.push(`  --spk-${i + 1}: ${c};`));
      lines.push('}');
      chunks.push(lines.join('\n'), '');
    }
  }

  fs.writeFileSync(OUT, chunks.join('\n'));
  // Data mirror for the main process (CJS cannot import the ESM source of truth):
  // used for BrowserWindow.backgroundColor so the pre-paint flash matches the theme.
  fs.writeFileSync(OUT_JSON, JSON.stringify(THEMES, null, 2) + '\n');
  console.log(`wrote ${OUT} (${THEMES.length} themes x 2 modes)`);
  console.log(`wrote ${OUT_JSON}`);
}

main().catch((err) => { console.error(err); process.exit(1); });
