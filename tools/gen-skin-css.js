#!/usr/bin/env node
'use strict';
/**
 * Generates src/renderer/theme/skins.css and skins.json from
 * src/renderer/theme/skins.js (the single source of truth for Phase II skins).
 *
 * A skin block overrides only the chroma tokens; the Tech Moca structure tokens
 * stay locked. Regenerate after editing skins.js:
 *
 *   node tools/gen-skin-css.js
 */
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const OUT = path.join(ROOT, 'src', 'renderer', 'theme', 'skins.css');
const OUT_JSON = path.join(ROOT, 'src', 'renderer', 'theme', 'skins.json');

async function main() {
  const { SKINS, skinCssTokens } = await import(
    'file:///' + path.join(ROOT, 'src', 'renderer', 'theme', 'skins.js').replace(/\\/g, '/')
  );

  const chunks = [
    '/* susurroLive — Phase II colour skins. GENERATED by tools/gen-skin-css.js from',
    ' * src/renderer/theme/skins.js.',
    ' *',
    ' * A skin overrides only the chroma tokens. The floor, lines, text, type,',
    ' * spacing, radius, shadow and motion tokens stay Tech Moca. Do not edit by hand.',
    ' */',
    '',
  ];

  for (const skin of SKINS) {
    for (const mode of ['dark', 'light']) {
      const tokens = skinCssTokens(skin.id, mode);
      const lines = [`[data-skin="${skin.id}"][data-theme-mode="${mode}"] {`];
      lines.push(`  /* ${skin.name} — ${skin.note} */`);
      for (const [k, v] of Object.entries(tokens)) lines.push(`  ${k}: ${v};`);
      lines.push('}');
      chunks.push(lines.join('\n'), '');
    }
  }

  fs.writeFileSync(OUT, chunks.join('\n'));
  fs.writeFileSync(OUT_JSON, JSON.stringify(SKINS, null, 2) + '\n');
  console.log(`wrote ${OUT} (${SKINS.length} skins x 2 modes)`);
  console.log(`wrote ${OUT_JSON}`);
}

main().catch((err) => { console.error(err); process.exit(1); });
